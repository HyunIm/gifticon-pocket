// Writes the offline file list (with SHA-256 integrity hashes) into dist/sw.js.
// Every file in dist is part of the app shell except the service worker itself and the
// text recognition engine in dist/vendor, which is cached on first use instead.
import { createHash } from 'node:crypto';
import { readFile, readdir, writeFile } from 'node:fs/promises';

const dist = new URL('../dist/', import.meta.url);
const worker = new URL('sw.js', dist);

async function walk(dir, base = '') {
  const files = [];
  for (const entry of await readdir(new URL(base, dir), { withFileTypes: true })) {
    const path = base + entry.name;
    if (entry.name.startsWith('.') || entry.name.startsWith('_')) continue;
    if (entry.isDirectory()) {
      if (path !== 'vendor') files.push(...await walk(dir, path + '/'));
    } else if (path !== 'sw.js') {
      files.push(path);
    }
  }
  return files;
}

const shellFiles = (await walk(dist)).sort();
const entries = await Promise.all(shellFiles.map(async file => {
  const bytes = await readFile(new URL(file, dist));
  const hash = createHash('sha256').update(bytes).digest('base64');
  return [file === 'index.html' ? '/' : '/' + file, 'sha256-' + hash];
}));
const vendors = (await readdir(new URL('vendor/', dist)).catch(() => [])).filter(name => name.startsWith('tesseract-'));
if (vendors.length !== 1) throw new Error(`Expected one dist/vendor/tesseract-* directory, found ${vendors.length}. Run npm run vendor.`);
const vendorDir = `/vendor/${vendors[0]}/`;
const manifest = JSON.stringify(Object.fromEntries(entries), null, 2);
const revision = createHash('sha256').update(manifest + vendorDir).digest('hex').slice(0, 16);
const source = await readFile(worker, 'utf8');
const marker = '// End generated shell manifest';
const end = source.indexOf(marker);
if (end < 0) throw new Error('Offline shell manifest marker is missing from sw.js');
const output = [
  '// Generated by scripts/refresh-offline-cache.mjs',
  `const revision = '${revision}';`,
  `const shell = ${manifest};`,
  `const vendorDir = '${vendorDir}';`,
  source.slice(end),
].join('\n');
if (output !== source) await writeFile(worker, output);
console.log(`Offline shell: ${entries.length} files, revision ${revision}`);
