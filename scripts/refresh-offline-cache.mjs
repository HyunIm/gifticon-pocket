// Writes the offline file list (with SHA-256 integrity hashes) to dist/sw-manifest.js, which the
// service worker imports. Every file in dist is part of the app shell except the service worker
// files and the text recognition engine in dist/vendor, which is cached on first use instead.
// The output is not committed (.gitignore); deploys and `npm run build` generate it.
import { createHash } from 'node:crypto';
import { readFile, readdir, writeFile } from 'node:fs/promises';

const dist = new URL('../dist/', import.meta.url);
const output = new URL('sw-manifest.js', dist);

async function walk(dir, base = '') {
  const files = [];
  for (const entry of await readdir(new URL(base, dir), { withFileTypes: true })) {
    const path = base + entry.name;
    if (entry.name.startsWith('.') || entry.name.startsWith('_')) continue;
    if (entry.isDirectory()) {
      if (path !== 'vendor') files.push(...await walk(dir, path + '/'));
    } else if (path !== 'sw.js' && path !== 'sw-manifest.js') {
      files.push(path);
    }
  }
  return files;
}

const shellFiles = (await walk(dist)).sort();
const entries = await Promise.all(shellFiles.map(async file => {
  const bytes = await readFile(new URL(file, dist));
  const hash = createHash('sha256').update(bytes).digest('base64');
  return [file === 'index.html' ? './' : file, 'sha256-' + hash];
}));
const vendors = (await readdir(new URL('vendor/', dist)).catch(() => [])).filter(name => name.startsWith('tesseract-'));
if (vendors.length !== 1) throw new Error(`Expected one dist/vendor/tesseract-* directory, found ${vendors.length}. Run npm run vendor.`);
const vendorDir = `vendor/${vendors[0]}/`;
const manifest = JSON.stringify(Object.fromEntries(entries), null, 2);
// The worker itself counts too: changing only sw.js is also a new version.
const workerSource = await readFile(new URL('sw.js', dist));
const revision = createHash('sha256').update(manifest + vendorDir).update(workerSource).digest('hex').slice(0, 16);
const content = `// Generated by scripts/refresh-offline-cache.mjs; do not edit or commit.
self.OFFLINE_MANIFEST = ${JSON.stringify({ revision, vendorDir, shell: Object.fromEntries(entries) }, null, 2)};
`;
const previous = await readFile(output, 'utf8').catch(() => '');
if (content !== previous) await writeFile(output, content);
console.log(`Offline shell: ${entries.length} files, revision ${revision}`);
